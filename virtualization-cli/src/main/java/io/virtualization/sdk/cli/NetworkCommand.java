package io.virtualization.sdk.cli;

import picocli.CommandLine.Command;
import picocli.CommandLine.Model.CommandSpec;
import picocli.CommandLine.Spec;

import java.util.concurrent.Callable;

@Command(
        name = "network",
        description = "Manage provider-neutral networks.",
        subcommands = {NetworkListCommand.class, NetworkCreateCommand.class, NetworkGetCommand.class, NetworkDeleteCommand.class})
final class NetworkCommand implements Callable<Integer> {

    @Spec
    CommandSpec spec;

    @Override
    public Integer call() {
        spec.commandLine().usage(spec.commandLine().getOut());
        return ExitCodes.OK;
    }
}
