package io.virtualization.sdk.cli;

import picocli.CommandLine.Command;
import picocli.CommandLine.Model.CommandSpec;
import picocli.CommandLine.Spec;

import java.util.concurrent.Callable;

@Command(
        name = "project",
        description = "Manage provider-neutral projects.",
        subcommands = {ProjectListCommand.class, ProjectCreateCommand.class, ProjectGetCommand.class, ProjectDeleteCommand.class})
final class ProjectCommand implements Callable<Integer> {

    @Spec
    CommandSpec spec;

    @Override
    public Integer call() {
        spec.commandLine().usage(spec.commandLine().getOut());
        return ExitCodes.OK;
    }
}
